export const getStationId = (stationName: string): number => {
  const stationId = STATION_ID_MAP[stationName];
  if (stationId) {
    return stationId;
  }

  let hash = 0;
  for (let i = 0; i < stationName.length; i++) {
    const char = stationName.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash;
  }
  return Math.abs(hash % 9000) + 1000;
};

export const getStationName = (stationId: number): string | null => {
  const entry = Object.entries(STATION_ID_MAP).find(([_, id]) => id === stationId);
  return entry ? entry[0] : null;
};
